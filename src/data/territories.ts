export const TERRITORY_STATES: string[] = Array.from(
  new Set(TERRITORIES.map((t) => t.state))
).sort();

// Pre-indexed map of state to all covered cities (lowercase for quick lookup)
export const STATE_TO_CITIES: Record<string, string[]> = TERRITORIES.reduce((acc, t) => {
  if (!acc[t.state]) {
    acc[t.state] = [];
  }
  t.cities.forEach((c) => {
    if (!acc[t.state].includes(c)) {
      acc[t.state].push(c);
    }
  });
  return acc;
}, {} as Record<string, string[]>);

// Pre-indexed map of state to territories
export const STATE_TO_TERRITORIES: Record<string, Territory[]> = TERRITORIES.reduce((acc, t) => {
  if (!acc[t.state]) {
    acc[t.state] = [];
  }
  acc[t.state].push(t);
  return acc;
}, {} as Record<string, Territory[]>);

/**
 * Normalizes a city/location string for fuzzy comparison
 */
export function normalizeLocationStr(str?: string): string {
  if (!str) return '';
  return str
    .toLowerCase()
    .replace(/[\(\)\-\/\,\.]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Checks if a city belongs to a specific state based on the master territories file
 */
export function isCityInState(cityName?: string, stateName?: string): boolean {
  if (!cityName || !stateName) return false;
  const normState = stateName.toLowerCase().trim();
  const normCity = normalizeLocationStr(cityName);

  // Check state directly
  const stateEntry = Object.keys(STATE_TO_CITIES).find(
    (s) => s.toLowerCase() === normState || normState.includes(s.toLowerCase()) || s.toLowerCase().includes(normState)
  );

  if (!stateEntry) return false;

  const citiesInState = STATE_TO_CITIES[stateEntry] || [];
  return citiesInState.some((c) => {
    const nc = normalizeLocationStr(c);
    return normCity.includes(nc) || nc.includes(normCity);
  });
}

/**
 * Gets all cities for a specific state
 */
export function getCitiesForState(stateName: string): string[] {
  if (!stateName || stateName === 'ALL') return [];
  const stateEntry = Object.keys(STATE_TO_CITIES).find(
    (s) => s.toLowerCase() === stateName.toLowerCase().trim()
  );
  return stateEntry ? STATE_TO_CITIES[stateEntry] : [];
}

/**
 * Gets all territories for a specific state
 */
export function getTerritoriesForState(stateName: string): Territory[] {
  if (!stateName || stateName === 'ALL') return TERRITORIES;
  const stateEntry = Object.keys(STATE_TO_TERRITORIES).find(
    (s) => s.toLowerCase() === stateName.toLowerCase().trim()
  );
  return stateEntry ? STATE_TO_TERRITORIES[stateEntry] : [];
}

/**
 * Finds the specific territory covering a city and optional state
 */
export function findTerritoryByCity(cityName?: string, stateName?: string): Territory | undefined {
  if (!cityName) return undefined;
  const normCity = normalizeLocationStr(cityName);
  const normState = stateName ? stateName.toLowerCase().trim() : '';

  // 1. Try exact or sub-string city match within matching state first
  if (normState) {
    const stateTerritories = getTerritoriesForState(stateName!);
    for (const terr of stateTerritories) {
      for (const c of terr.cities) {
        const nc = normalizeLocationStr(c);
        if (normCity === nc || normCity.includes(nc) || nc.includes(normCity)) {
          return terr;
        }
      }
    }
  }

  // 2. Global search across all territories
  for (const terr of TERRITORIES) {
    for (const c of terr.cities) {
      const nc = normalizeLocationStr(c);
      if (normCity === nc || normCity.includes(nc) || nc.includes(normCity)) {
        return terr;
      }
    }
  }

  // 3. Fallback: match by state if city didn't hit a specific city
  if (normState) {
    const stateTerritories = getTerritoriesForState(stateName!);
    if (stateTerritories.length > 0) {
      return stateTerritories[0];
    }
  }

  return undefined;
}

export interface ChannelPartnerSuggestion {
  partner?: any;
  territory?: Territory;
  matchedCity?: string;
  confidence: number;
  matchReason: string;
}

/**
 * Compares lead city/state with all 100 territories and identifies the matching Channel Partner (CP-001..CP-100)
 */
export function findSuggestedChannelPartner(
  lead: { location?: { city?: string; state?: string; address?: string } },
  channelPartners: any[] = []
): ChannelPartnerSuggestion {
  const city = lead.location?.city || '';
  const state = lead.location?.state || '';
  const address = lead.location?.address || '';

  // 1. Try finding territory from city & state
  let territory = findTerritoryByCity(city, state);
  let matchedCity = '';

  if (territory && city) {
    const normCity = normalizeLocationStr(city);
    matchedCity =
      territory.cities.find((c) => {
        const nc = normalizeLocationStr(c);
        return normCity === nc || normCity.includes(nc) || nc.includes(normCity);
      }) || territory.cities[0];
  }

  // 2. If no territory found by city, try searching in address
  if (!territory && address) {
    const normAddr = normalizeLocationStr(address);
    for (const t of TERRITORIES) {
      const foundCity = t.cities.find((c) => normAddr.includes(normalizeLocationStr(c)));
      if (foundCity) {
        territory = t;
        matchedCity = foundCity;
        break;
      }
    }
  }

  // 3. Fallback: match by state
  if (!territory && state) {
    const stateTerrs = getTerritoriesForState(state);
    if (stateTerrs.length > 0) {
      territory = stateTerrs[0];
      matchedCity = territory.cities[0];
    }
  }

  if (!territory) {
    return {
      partner: channelPartners[0],
      territory: undefined,
      matchedCity: '',
      confidence: 0,
      matchReason: 'No territory match found',
    };
  }

  // Find channel partner matching this territoryId (e.g. 'CP-001' or 'ch001')
  const matchedPartner =
    channelPartners.find(
      (cp) =>
        cp.territory_id === territory!.territoryId ||
        cp.id === territory!.territoryId ||
        cp.id?.toLowerCase() === territory!.territoryId.toLowerCase() ||
        cp.name?.includes(territory!.territoryId) ||
        (cp.territory_name && cp.territory_name.toLowerCase() === territory!.territoryName.toLowerCase())
    ) ||
    channelPartners.find((cp) => cp.state?.toLowerCase() === territory!.state.toLowerCase()) ||
    channelPartners[0];

  return {
    partner: matchedPartner,
    territory,
    matchedCity: matchedCity || territory.cities[0],
    confidence: matchedCity ? 0.96 : 0.75,
    matchReason: matchedCity
      ? `City "${matchedCity}" mapped to ${territory.territoryId} (${territory.territoryName})`
      : `Regional state match for ${territory.state} (${territory.territoryId})`,
  };
}

